export function isLanguageCode(val: unknown): val is LanguageCode {
  return (
    val === 'en' ||
    val === 'ru' ||
    val === 'es' ||
    val === 'fr' ||
    val === 'de' ||
    val === 'pt' ||
    val === 'tr'
  );
}

export function normalizeLanguageCode(val: unknown, fallback: LanguageCode = 'en'): LanguageCode {
  if (typeof val !== 'string') return fallback;
  const trimmed = val.trim().toLowerCase();
  if (isLanguageCode(trimmed)) return trimmed;
  const prefix = trimmed.split(/[-_]/)[0];
  return isLanguageCode(prefix) ? prefix : fallback;
}

export function detectBrowserLanguage(): LanguageCode {
  if (typeof navigator === 'undefined') return 'en';
  const raw = navigator.language || (navigator.languages && navigator.languages[0]) || 'en';
  return normalizeLanguageCode(raw, 'en');
}

